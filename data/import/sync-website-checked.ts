/**
 * Writes data/website-checked.ts: for each venue, the last date its website
 * was confirmed live. The listing page shows it as "Website checked <date>".
 *
 * Sources (all in data/import/, git-ignored like the other import CSVs):
 *  - website-check-YYYY-MM-DD.csv (check-venue-websites.ts): rows with
 *    verdict "ok" count, dated by the file name
 *  - website-fixes.csv: a replacement website found by a verification run
 *    counts too, dated by the date in its source file name
 * A venue whose current website differs from the one checked is left out,
 * so a later website change never shows an old check date.
 *
 * Run after a website check or new website fixes:
 *   npx tsx data/import/sync-website-checked.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parse } from "csv-parse/sync";
import type { Listing } from "../../lib/types";

const IMPORT_DIR = path.join(process.cwd(), "data", "import");
const GENERATED_FILE = path.join(process.cwd(), "data", "generated-listings.json");
const OUT_FILE = path.join(process.cwd(), "data", "website-checked.ts");

const sameSite = (a: string, b: string) => a.replace(/\/+$/, "").toLowerCase() === b.replace(/\/+$/, "").toLowerCase();
const dateIn = (s: string) => s.match(/\d{4}-\d{2}-\d{2}/)?.[0];

const listings: Listing[] = JSON.parse(readFileSync(GENERATED_FILE, "utf-8"));
const currentSite = new Map(listings.map((l) => [l.slug, l.websiteUrl ?? ""]));
const checked = new Map<string, string>();
const record = (slug: string, url: string, date: string) => {
  const current = currentSite.get(slug);
  if (!current || !sameSite(current, url)) return;
  if ((checked.get(slug) ?? "") < date) checked.set(slug, date);
};

for (const file of readdirSync(IMPORT_DIR).filter((f) => /^website-check-\d{4}-\d{2}-\d{2}\.csv$/.test(f))) {
  const date = dateIn(file)!;
  const rows = parse(readFileSync(path.join(IMPORT_DIR, file), "utf-8"), { columns: true }) as {
    verdict: string;
    slug: string;
    websiteUrl: string;
  }[];
  for (const r of rows) if (r.verdict === "ok") record(r.slug, r.websiteUrl, date);
}

const fixes = parse(readFileSync(path.join(IMPORT_DIR, "website-fixes.csv"), "utf-8"), { columns: true }) as {
  slug: string;
  websiteUrl: string;
  source: string;
}[];
for (const f of fixes) {
  const date = dateIn(f.source);
  if (date && f.websiteUrl) record(f.slug, f.websiteUrl, date);
}

const entries = [...checked.entries()].sort(([a], [b]) => a.localeCompare(b));
writeFileSync(
  OUT_FILE,
  `// Generated by data/import/sync-website-checked.ts. Do not edit by hand.\n` +
    `// slug -> date (YYYY-MM-DD) the venue's current website was last confirmed live.\n` +
    `export const WEBSITE_CHECKED: Record<string, string> = {\n` +
    entries.map(([slug, date]) => `  ${JSON.stringify(slug)}: "${date}",`).join("\n") +
    `\n};\n`,
);
console.log(`${entries.length} venues with a checked website -> ${OUT_FILE}`);
